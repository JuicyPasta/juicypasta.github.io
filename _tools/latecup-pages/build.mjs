// Builds Latecup's neighbourhood pages from the live feed:
//   latecup/nyc/index.html                    (all neighbourhoods, by borough)
//   latecup/nyc/<neighbourhood>/index.html    ("Coffee shops open late in the East Village")
// and rewrites the Latecup lines of sitemap.xml. Only facts that don't depend on tonight:
// usual closing time per night, where the hours come from. A neighbourhood gets a page
// when it has 3 or more places in the feed (the feed holds only places that close at
// 8 PM or later on at least one night).
//
// Usage, from the repo root:  node _tools/latecup-pages/build.mjs [--feed <url or folder>] [--force]
// The workflow .github/workflows/latecup-pages.yml runs it twice a day after the feed's refreshes.
// The folder starts with _ so it is not published.
//
// A bad feed can never blank the pages: the feed is fetched and checked before anything is
// deleted or written, and when it is unreachable or fails a check the script exits with
// code 3 having touched nothing (the workflow treats 3 as "nothing to do"). Checks: format 1,
// the places file matches the manifest's sha256, at least 200 places and 10 neighbourhoods,
// under 5% malformed places, and not under half the places the current pages were built
// from (--force skips that last one, for a real, deliberate shrink).
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const H = createRequire(import.meta.url)(join(ROOT, 'latecup', 'hours.js'));
const V = createRequire(import.meta.url)(join(ROOT, 'latecup', 'votes.js'));
const SITE = 'https://juicypasta.github.io/latecup/';
const MARK = '<!-- generated by _tools/latecup-pages/build.mjs: do not edit by hand -->';
const MIN_PLACES = 3;
const arg = (name) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : null; };
const FEED = (arg('--feed') || 'https://juicypasta.github.io/latecup-data/v1/').replace(/\/?$/, '/');
const unusable = (why) => { console.error(`FEED NOT USABLE, nothing written: ${why}`); process.exit(3); };
const raw = async (name) => { // the file's bytes, from a URL or a folder
  if (!/^https?:/.test(FEED)) return readFileSync(FEED + name);
  const r = await fetch(FEED + name, { signal: AbortSignal.timeout(30000), headers: { 'cache-control': 'no-cache' } });
  if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
  return Buffer.from(await r.arrayBuffer());
};
const get = async (name) => JSON.parse((await raw(name)).toString('utf8'));
const MIN_PLACES_IN_FEED = 200, MIN_HOODS = 10, MAX_MALFORMED = 0.05;

const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const slug = (s) => s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/['’.]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const CAT = { coffee: 'Coffee', tea: 'Tea & boba', dessert: 'Dessert café' };
const BOROS = ['Manhattan', 'Brooklyn', 'Queens', 'Bronx', 'Staten Island'];
// "in the East Village", "on the Upper West Side", "on Roosevelt Island", "in Astoria"
const THE = /^(East Village|West Village|Financial District|Flatiron District|Garment District|Meatpacking District|Theater District|Rockaways|Bronx)$/;
const where = (hood) => (/ Side$/.test(hood) ? 'on the ' : / Island$/.test(hood) && hood !== 'Coney Island' && hood !== 'Long Island City' ? 'on ' : THE.test(hood) ? 'in the ' : 'in ') + hood;
const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`;
const list = (a) => (a.length <= 1 ? a.join('') : a.slice(0, -1).join(', ') + ' and ' + a[a.length - 1]);

// ---------- fetch and check the feed; nothing on disk has been touched yet ----------
let manifest, city, feed, places;
try {
  manifest = await get('manifest.json');
  if (manifest.format !== 1 || !Array.isArray(manifest.cities) || !manifest.cities[0] || !manifest.cities[0].places) unusable('the manifest is not format 1 or names no city');
  city = manifest.cities[0];
  const bytes = await raw(city.places);
  if (city.sha256 && createHash('sha256').update(bytes).digest('hex') !== city.sha256) unusable(`${city.places} does not match the manifest's sha256 (a refresh may be half published)`);
  feed = JSON.parse(bytes.toString('utf8'));
} catch (e) { unusable(`could not read the feed at ${FEED} (${e.message})`); }
if (feed.format !== 1 || !Array.isArray(feed.places)) unusable('the places file is not format 1');
const wellFormed = (p) => p && typeof p.id === 'string' && typeof p.name === 'string' && p.name && typeof p.hood === 'string' && p.hood && typeof p.boro === 'string'
  && typeof p.addr === 'string' && Number.isFinite(p.lat) && Number.isFinite(p.lon) && Array.isArray(p.hours) && p.hours.length === 7
  && p.hours.every((d) => Array.isArray(d) && d.every((iv) => Array.isArray(iv) && iv.length === 2 && Number.isFinite(iv[0]) && Number.isFinite(iv[1]) && iv[0] < iv[1]));
places = feed.places.filter(wellFormed);
if (feed.places.length - places.length > feed.places.length * MAX_MALFORMED) unusable(`${feed.places.length - places.length} of ${feed.places.length} places are malformed`);
if (places.length < MIN_PLACES_IN_FEED) unusable(`only ${places.length} places (need ${MIN_PLACES_IN_FEED})`);
if (!/^\d{4}-\d\d-\d\dT/.test(city.updated || '') || !city.tz) unusable('the city has no updated time or time zone');
{ // against what the pages on disk were built from
  const idx = join(ROOT, 'latecup', 'nyc', 'index.html');
  const before = existsSync(idx) ? +(/<!-- places: (\d+) -->/.exec(readFileSync(idx, 'utf8')) || [])[1] || 0 : 0;
  if (before && places.length < before / 2 && !process.argv.includes('--force')) unusable(`${places.length} places, under half of the ${before} the current pages were built from (run with --force if that is real)`);
}
// Visitor confirmations and star ratings: an optional file. Without it the pages simply say nothing about them.
let votes = {};
if (city.votes) { try { const v = await get(city.votes); if (v && v.votes && typeof v.votes === 'object') votes = v.votes; } catch { console.warn(`no votes file (${city.votes}): pages built without visitor counts`); } }
const sum = (p) => V.summary(p, votes[p.id]);
const updated = new Intl.DateTimeFormat('en-CA', { timeZone: city.tz, year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date(city.updated)); // the city's date, YYYY-MM-DD

// group by neighbourhood; a name that shows up in two boroughs is a data error: skip it and say so
const groups = new Map();
for (const p of places) { if (!groups.has(p.hood)) groups.set(p.hood, []); groups.get(p.hood).push(p); }
const hoods = [];
for (const [name, ps] of groups) {
  const boros = [...new Set(ps.map((p) => p.boro))];
  if (boros.length > 1) { console.warn(`skipped "${name}": its ${ps.length} places are in ${boros.join(' and ')} (feed error)`); continue; }
  if (ps.length < MIN_PLACES) continue;
  hoods.push({ name, slug: slug(name), boro: boros[0], places: ps });
}
hoods.sort((a, b) => a.name.localeCompare(b.name));
if (new Set(hoods.map((h) => h.slug)).size !== hoods.length) unusable('two neighbourhoods share a slug');
if (hoods.length < MIN_HOODS) unusable(`only ${hoods.length} neighbourhoods with ${MIN_PLACES} or more places (need ${MIN_HOODS})`);

const facts = (ps) => {
  const late = (rel) => ps.filter((p) => { for (let d = 0; d < 7; d++) { const t = H.tonight(p.hours, d); if (t && (t.allDay || t.close > rel)) return true; } return false; }).length;
  return { n: ps.length, ten: late(1320), midnight: late(1440), allDay: ps.filter((p) => H.latestClose(p.hours) === Infinity).length,
           confirmed: ps.filter((p) => p.src === 'shop' || p.src === 'brand').length, shop: ps.filter((p) => p.src === 'shop').length, brand: ps.filter((p) => p.src === 'brand').length, indie: ps.filter((p) => !p.chain).length,
           byVisitors: ps.filter((p) => p.src === 'osm' && sum(p).byVisitors).length, rated: ps.filter((p) => sum(p).stars).length };
};
const head = (title, desc, path, ld) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<link rel="canonical" href="${SITE}${path}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Latecup">
<meta property="og:title" content="${esc(title.replace(' | Latecup', ''))}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${SITE}${path}">
<meta property="og:image" content="${SITE}og.png">
<meta name="twitter:card" content="summary_large_image">
<link rel="icon" href="${'../'.repeat(path.split('/').length - 1)}icon.png">
<link rel="stylesheet" href="${'../'.repeat(path.split('/').length - 1)}style.css">
${ld.map((x) => `<script type="application/ld+json">${JSON.stringify(x).replace(/</g, '\\u003c')}</script>`).join('\n')}
</head>
<body>
${MARK}
<main class="text">`;
const foot = (up) => `<footer class="page">
<p><a href="${up}">Latecup map</a> · <a href="${up}#help">Help</a> · <a href="${up}privacy.html">Privacy policy</a> · Places and unconfirmed hours © <a href="https://www.openstreetmap.org/copyright">OpenStreetMap contributors</a> (ODbL)</p>
<p>Latecup is made by Jackson Darrow in New York City. It is not affiliated with any shop or chain listed here.</p>
</footer>
</main>
</body>
</html>
`;
const closings = (p) => H.weekClosings(p.hours).map((g) => `<span>${esc(g.days)} <b>${esc(g.text)}</b></span>`).join('');
const source = (p) => {
  const v = sum(p);
  return (p.src !== 'shop' && p.src !== 'brand' ? `<span class="tag">Unconfirmed${p.checked ? ', OSM ' + esc(p.checked) : ''}</span>` : `<span class="tag ok">✓ ${p.src === 'brand' ? 'Chain\'s store locator' : 'Shop\'s own site or page'}, ${esc(p.checked)}</span>`)
    + (v.flaggedLine ? `<span class="tag warn">${esc(v.flaggedLine)}</span>` : v.visitorLine ? `<span class="tag${v.byVisitors ? ' ok' : ''}">${esc(v.visitorLine)}</span>` : '')
    + (v.stars ? `<span class="tag star">★ ${v.stars.mean.toFixed(1)} · ${v.stars.n} ${v.stars.n === 1 ? 'rating' : 'ratings'}</span>` : '');
};

// ---------- one page per neighbourhood ----------
const outDir = join(ROOT, 'latecup', 'nyc');
mkdirSync(outDir, { recursive: true });
for (const d of readdirSync(outDir, { withFileTypes: true })) { // drop pages from an earlier run
  const f = join(outDir, d.name, 'index.html');
  if (d.isDirectory() && existsSync(f) && readFileSync(f, 'utf8').includes(MARK)) rmSync(join(outDir, d.name), { recursive: true });
}
for (const h of hoods) {
  const f = facts(h.places), w = where(h.name), path = `nyc/${h.slug}/`;
  const sorted = [...h.places].sort((a, b) => H.latestClose(b.hours) - H.latestClose(a.hours) || (a.chain ? 1 : 0) - (b.chain ? 1 : 0) || a.name.localeCompare(b.name));
  const latest = sorted[0];
  const until = (p) => { const c = H.latestClose(p.hours); return c === Infinity ? `${p.name} is open 24 hours` : `${p.name} stays open until ${H.clock(c)} on its latest night`; };
  const indie = sorted.find((p) => !p.chain);
  const latestText = until(latest) + (latest.chain && indie ? `. The latest independent shop: ${until(indie)}` : '');
  const title = `Coffee shops open late ${w}, NYC | Latecup`;
  const desc = `${plural(f.n, 'coffee shop, tea house or dessert café', 'coffee shops, tea houses and dessert cafés')} ${w} that ${f.n === 1 ? 'closes' : 'close'} at 8 PM or later, with the usual closing time for each night. ${latestText}.`;
  const bits = [];
  if (f.ten) bits.push(`${f.ten} ${f.ten === 1 ? 'is' : 'are'} open past 10 PM on at least one night`);
  if (f.midnight) bits.push(`${f.midnight} past midnight`);
  if (f.allDay) bits.push(`${f.allDay} ${f.allDay === 1 ? 'is' : 'are'} open 24 hours`);
  const conf = f.confirmed === 0 ? 'None of these hours has been confirmed by us yet: they come from OpenStreetMap, so check with the shop before a late trip.'
    : `We confirmed the hours of ${f.confirmed === f.n ? (f.n === 1 ? 'it' : 'all of them') : f.confirmed + ' of them'} (marked ✓): ${[f.shop ? `${f.shop} from the shop's own site or page` : '', f.brand ? `${f.brand} from the chain's store locator` : ''].filter(Boolean).join(' and ')}.`
      + (f.confirmed === f.n ? '' : ' The rest come from OpenStreetMap and are marked unconfirmed, so check before a late trip.');
  const visitors = f.byVisitors ? ` Visitors have confirmed the hours of ${f.byVisitors} more (two or more people each).` : '';
  const others = hoods.filter((o) => o.boro === h.boro && o.slug !== h.slug).sort((a, b) => b.places.length - a.places.length).slice(0, 10).sort((a, b) => a.name.localeCompare(b.name));
  const ld = [
    { '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Latecup', item: SITE }, { '@type': 'ListItem', position: 2, name: 'New York City', item: SITE + 'nyc/' },
      { '@type': 'ListItem', position: 3, name: h.name, item: SITE + path }] },
    { '@context': 'https://schema.org', '@type': 'ItemList', name: `Coffee shops open late ${w}`, numberOfItems: sorted.length,
      itemListElement: sorted.map((p, i) => ({ '@type': 'ListItem', position: i + 1, item: { '@type': 'CafeOrCoffeeShop', name: p.name,
        address: { '@type': 'PostalAddress', streetAddress: p.addr, addressLocality: h.boro === 'Manhattan' ? 'New York' : h.boro, addressRegion: 'NY', addressCountry: 'US' },
        geo: { '@type': 'GeoCoordinates', latitude: p.lat, longitude: p.lon } } })) },
  ];
  const html = `${head(title, desc, path, ld)}
<p class="crumbs"><a href="../../">Latecup</a> › <a href="../">New York City</a> › ${esc(h.name)}</p>
<header class="page">
<img src="../../icon.png" alt="">
<div><h1>Coffee shops open late ${esc(w)}</h1><p>${esc(h.boro)}, New York City · list updated ${updated}</p></div>
</header>

<p>Latecup lists ${plural(f.n, 'coffee shop, tea house or dessert café', 'coffee shops, tea houses and dessert cafés')} ${esc(w)} that ${f.n === 1 ? 'closes' : 'close'} at 8 PM or later on at least one night${bits.length ? ': ' + esc(list(bits)) : ''}. ${esc(latestText)}.</p>
<p>${esc(conf + visitors)}</p>
<p><a class="btn" href="../../#hood=${encodeURIComponent(h.name)}">See them on the map, with tonight's closing times</a></p>

<h2>Usual closing times ${esc(w)}</h2>
<table class="places">
<tr><th>Place</th><th>Closes</th><th>Hours</th></tr>
${sorted.map((p) => `<tr><td><a class="name" href="../../#p=${encodeURIComponent(p.id)}">${esc(p.name)}</a><span class="sub">${esc(p.addr)} · ${esc(CAT[p.cat] || p.cat)}</span></td><td class="closings">${closings(p)}</td><td>${source(p)}</td></tr>`).join('\n')}
</table>
<p class="small muted">Closing times are the end of each night's last opening, so "1 AM" on Friday means 1 AM on Saturday morning. A night runs until 5 AM. Hours change on holidays, and a shop can close early without notice.</p>

<h2>How to read this list</h2>
<ul>
<li><strong>✓</strong> means we confirmed the hours on the date shown, and says from where: "Shop's own site or page" (its website, ordering page or official social account) or "Chain's store locator".</li>
<li><strong>Unconfirmed</strong> hours come from <a href="https://www.openstreetmap.org/">OpenStreetMap</a>, a map kept up by volunteers. The date, when there is one, is when someone last checked them there.</li>
<li><strong>Visitors</strong> can confirm a place's hours and rate it from 1 to 5 stars on <a href="../../">the map</a>. Where they have, this list shows how many confirmed the hours now shown, and the star average with its number of ratings.</li>
<li>Seen a wrong time? Open the place on <a href="../../">the map</a> and choose "Hours wrong?".</li>
</ul>
${others.length ? `
<h2>More late coffee in ${esc(h.boro === 'Bronx' ? 'the Bronx' : h.boro)}</h2>
<ul class="hoods">
${others.map((o) => `<li><a href="../${o.slug}/">${esc(o.name)}</a><span class="n">${o.places.length}</span></li>`).join('\n')}
</ul>
<p><a href="../">All New York City neighbourhoods</a></p>` : '<p><a href="../">All New York City neighbourhoods</a></p>'}
${foot('../../')}`;
  mkdirSync(join(outDir, h.slug), { recursive: true });
  writeFileSync(join(outDir, h.slug, 'index.html'), html);
}

// ---------- the index ----------
{
  const f = facts(places), moreThan = (n) => (n > 50 ? 'more than ' + Math.floor((n - 1) / 50) * 50 : String(n)), cap = (t) => t[0].toUpperCase() + t.slice(1);
  const title = 'Coffee shops open late in New York City, by neighbourhood | Latecup';
  const desc = `Late-night coffee shops, tea houses and dessert cafés in ${hoods.length} New York City neighbourhoods, with the usual closing time for each night and where the hours come from.`;
  const html = `${head(title, desc, 'nyc/', [{ '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [
    { '@type': 'ListItem', position: 1, name: 'Latecup', item: SITE }, { '@type': 'ListItem', position: 2, name: 'New York City', item: SITE + 'nyc/' }] }])}
<!-- places: ${places.length} -->
<p class="crumbs"><a href="../">Latecup</a> › New York City</p>
<header class="page">
<img src="../icon.png" alt="">
<div><h1>Coffee shops open late in New York City</h1><p>By neighbourhood · list updated ${updated}</p></div>
</header>

<p>Latecup lists ${moreThan(f.n)} coffee shops, tea houses and dessert cafés across the five boroughs that close at 8 PM or later on at least one night. ${cap(moreThan(f.ten))} of them are open past 10 PM on some night, and ${moreThan(f.midnight)} past midnight. Pick a neighbourhood for the usual closing times, or open <a href="../">the map</a> to see what is open tonight and until when.</p>
<p><a class="btn" href="../">Open the map</a></p>
${BOROS.map((b) => {
    const hs = hoods.filter((h) => h.boro === b);
    return hs.length ? `
<h2>${b === 'Bronx' ? 'The Bronx' : b}</h2>
<ul class="hoods">
${hs.map((h) => `<li><a href="${h.slug}/">${esc(h.name)}</a><span class="n">${h.places.length}</span></li>`).join('\n')}
</ul>` : '';
  }).join('\n')}
<p class="small muted">The number beside a neighbourhood is the number of places on its page: those that close at 8 PM or later on at least one night. Neighbourhoods with fewer than ${MIN_PLACES} are on the map only.${f.confirmed ? '' : ' Hours come from OpenStreetMap until we confirm them from the shop\'s own site or page or the chain\'s store locator; unconfirmed hours are labelled.'}</p>
${foot('../')}`;
  writeFileSync(join(outDir, 'index.html'), html);
}

// ---------- sitemap: replace only the Latecup lines ----------
{
  const file = join(ROOT, 'sitemap.xml'), today = new Intl.DateTimeFormat('en-CA', { timeZone: city.tz, year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
  const old = readFileSync(file, 'utf8').split('\n');
  const was = (u) => (new RegExp(`<loc>${(SITE + u).replace(/[.]/g, '\\.')}</loc><lastmod>([0-9-]+)</lastmod>`).exec(old.join('\n')) || [])[1]; // hand-written pages keep their date
  const kept = old.filter((l) => !l.includes(`<loc>${SITE}`));
  const end = kept.findIndex((l) => l.includes('</urlset>'));
  const urls = ['', 'privacy.html', 'nyc/', ...hoods.map((h) => `nyc/${h.slug}/`)].map((u) => `  <url><loc>${SITE}${u}</loc><lastmod>${u.startsWith('nyc/') ? updated : was(u) || today}</lastmod></url>`);
  kept.splice(end, 0, ...urls);
  writeFileSync(file, kept.join('\n'));
}
console.log(`${hoods.length} neighbourhood pages + index from ${places.length} places (feed updated ${updated}); sitemap has ${hoods.length + 3} Latecup URLs`);
